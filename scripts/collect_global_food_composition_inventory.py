def source(**kwargs: Any) -> dict[str, Any]:
    """Build a registry entry and make deliberately omitted fields explicit."""
    required = {
        "source_key",
        "name",
        "region",
        "countries_or_coverage",
        "scope",
        "data_kind",
        "reported_foods",
        "reported_components",
        "measurement_provenance",
        "access_status",
        "license_or_terms",
        "foundation_model_role",
        "suitability",
        "limitations",
        "official_url",
        "download_url",
        "local_raw_path",
    }
    missing = required - set(kwargs)
    if missing:
        raise ValueError(f"Incomplete source registry entry: {sorted(missing)}")
    return kwargs


