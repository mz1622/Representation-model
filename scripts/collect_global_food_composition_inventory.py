def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def valid_artifact(path: Path) -> bool:
    """Reject HTML error pages masquerading as a spreadsheet or PDF download."""
    header = path.read_bytes()[:8]
    suffix = path.suffix.lower()
    if suffix == ".pdf":
        return header.startswith(b"%PDF-")
    if suffix in {".xlsx", ".xlsm"}:
        return header.startswith(b"PK\x03\x04")
    return path.stat().st_size > 0


def download(url: str, destination: Path) -> dict[str, Any]:
    request = urllib.request.Request(url, headers={"User-Agent": "FoodNutritionSourceInventory/1.0 (research use)"})
    try:
        with urllib.request.urlopen(request, timeout=120) as response, destination.open("wb") as handle:
            shutil.copyfileobj(response, handle)
        if not valid_artifact(destination):
            destination.unlink(missing_ok=True)
            return {
                "status": "invalid_artifact",
                "url": url,
                "detail": "Response did not match the expected file signature; likely an access-control or error page.",
            }
        return {
            "status": "downloaded",
            "url": url,
            "path": str(destination.relative_to(ROOT)),
            "bytes": destination.stat().st_size,
            "sha256": sha256(destination),
        }
    except urllib.error.HTTPError as error:
        destination.unlink(missing_ok=True)
        return {"status": "http_error", "url": url, "http_status": error.code, "detail": str(error)}
    except urllib.error.URLError as error:
        destination.unlink(missing_ok=True)
        return {"status": "url_error", "url": url, "detail": str(error.reason)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true", help="Download directly accessible raw source artifacts.")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    DOWNLOAD_DIR.mkdir(parents=True, exist_ok=True)
    now = datetime.now(timezone.utc).isoformat()

    manifest: list[dict[str, Any]] = []
    for filename, url in DOWNLOADS.items():
        destination = DOWNLOAD_DIR / filename
        if destination.exists() and valid_artifact(destination):
            manifest.append(
                {
                    "status": "already_present",
                    "url": url,
                    "path": str(destination.relative_to(ROOT)),
                    "bytes": destination.stat().st_size,
                    "sha256": sha256(destination),
                }
            )
        elif destination.exists():
            destination.unlink()
            manifest.append(
                {
                    "status": "invalid_existing_artifact_removed",
                    "url": url,
                    "path": str(destination.relative_to(ROOT)),
                    "detail": "Existing file did not match the expected file signature.",
                }
            )
        elif args.download:
            manifest.append(download(url, destination))
        else:
            manifest.append({"status": "not_requested", "url": url, "path": str(destination.relative_to(ROOT))})

    fields = list(SOURCES[0].keys())
    with (OUT_DIR / "source_registry.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(SOURCES)

    (OUT_DIR / "source_registry.json").write_text(
        json.dumps({"as_of_utc": now, "no_merging_performed": True, "sources": SOURCES}, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    (OUT_DIR / "download_manifest.json").write_text(
        json.dumps({"as_of_utc": now, "no_merging_performed": True, "files": manifest}, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(SOURCES)} source registry entries to {OUT_DIR}")
    print(f"Direct artifact records: {len(manifest)}")


if __name__ == "__main__":
    main()
